// itemPriceFactors は値段を変える道具ごとの値（純粋な計算用）。
type itemPriceFactors struct {
	Category  string // ItemTemplate.ItemType（"Weapon"・"Cane" など）
	Sharpness int    // 武器・盾の強化値
	Cursed    bool
	Uses      int // 杖の残り回数
	Capacity  int // 壺の容量
	Count     int // 矢の本数
}

// itemBuyPriceFrom は基準 base と道具の値 f から買値を計算する。base が0（売買しない）なら0。
func itemBuyPriceFrom(base int, f itemPriceFactors) int {
	if base <= 0 {
		return 0
	}
	price := base
	switch f.Category {
	case "Weapon", "Armor":
		price = max(base*(5+f.Sharpness)/5, base/5)
	case "Cane":
		price = base + max(f.Uses, 0)*max(base/10, 50)
	case "Pot":
		price = base + max(f.Capacity, 0)*100
	case "Arrow":
		price = base * max(f.Count, 1)
	}
	if f.Cursed {
		price /= 2
	}
	return max(price, 1)
}

// itemSellPriceFromBuy は買値から売値を計算する（1未満にはしない。買値0は0）。
func itemSellPriceFromBuy(buy int) int {
	if buy <= 0 {
		return 0
	}
	return max(buy/itemSellDivisor, 1)
}
